/* 步骤构造器 */
function S(id, input, opts) {
  return Object.assign({ id, input }, opts || {})
}

/* 生成 n 个日常 filler 步骤（startIdx 用于轮换输入与时间） */
function fl(n, startIdx) {
  const out = []
  for (let i = 0; i < n; i++) {
    const k = startIdx + i
    const dlg = k % 12 === 7
    out.push({
      id: 'fl-' + k,
      input: FILLERS[k % FILLERS.length],
      adv: [1, TOD[k % 4]],
      b: dlg ? null : 'minor',
      dlg
    })
  }
  return out
}

